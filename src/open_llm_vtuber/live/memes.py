"""Curated Chinese internet memes for the live reply layer.

The cards are reference data, not instructions.  A card stores what a meme
means, when it fits, and where it should not be used, so the model can borrow
the *intent* instead of blindly pasting a phrase.

The 2026 research snapshot is documented in ``doc/hot-memes-2026.md``.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

__all__ = ["MemeCard", "MemeLibrary", "HOT_MEMES", "meme_system_guide"]

_SPACE = re.compile(r"[\s，,。.!！？?、~～·'\"“”‘’]+")


@dataclass(frozen=True)
class MemeCard:
    term: str
    aliases: tuple[str, ...]
    meaning: str
    usage: str
    tone: str
    avoid: str = ""
    source: str = ""

    def prompt_line(self, *, detailed: bool = False) -> str:
        base = f"- {self.term}：{self.meaning} 适合：{self.usage}"
        if detailed:
            base += f" 语气：{self.tone.rstrip('。')}。"
            if self.avoid:
                base += f" 不要：{self.avoid.rstrip('。')}。"
        return base


