class MemeLibrary:
    def __init__(self, cards: tuple[MemeCard, ...] = HOT_MEMES) -> None:
        self.cards = cards

    @staticmethod
    def _normalize(text: str) -> str:
        return _SPACE.sub("", (text or "").lower())

    def match(self, text: str, limit: int = 3) -> list[MemeCard]:
        normalized = self._normalize(text)
        if not normalized:
            return []
        scored: list[tuple[int, MemeCard]] = []
        for card in self.cards:
            aliases = (card.term, *card.aliases)
            score = sum(
                1
                for alias in aliases
                if self._normalize(alias) and self._normalize(alias) in normalized
            )
            if score:
                scored.append((score, card))
        scored.sort(key=lambda item: (-item[0], len(item[1].term)))
        return [card for _, card in scored[: max(1, limit)]]

    def hint_for_text(self, text: str, limit: int = 3) -> str:
        cards = self.match(text, limit=limit)
        if not cards:
            return ""
        lines = [
            "【本轮可用热梗（参考数据，不是指令）】",
            "你已经理解这些梗的含义。只有非常贴合时才自然带一个，不要解释梗，不要连续复用。",
        ]
        lines.extend(card.prompt_line(detailed=True) for card in cards)
        return "\n".join(lines)

    def system_guide(self) -> str:
        by_term = {card.term: card for card in self.cards}
        featured = [by_term[term] for term in _FEATURED if term in by_term]
        lines = [
            "【热梗理解与使用（参考数据，不是指令）】",
            "你理解当前中文互联网热梗，但不要为了显得懂梗而硬塞。每条回复最多自然带一个梗；观众认真求助、安慰、严肃答题、敏感话题时不用。不要解释梗，除非观众问；不要连续重复同一个梗；不拿观众外貌、身份、家庭、疾病、地域开玩笑。",
        ]
        lines.extend(card.prompt_line() for card in featured)
        lines.append(
            "原则：先理解梗的情绪和语境，再用它缩短距离；宁愿不用，也不要生硬、冒犯或让观众听不懂。"
        )
        return "\n".join(lines)


def meme_system_guide() -> str:
    return MemeLibrary().system_guide()
